/**
 * Which member profiles we ask search engines to index (LAB-3096).
 *
 * A profile with no bio and no photo is an empty page: a name and nothing else. It stays reachable, but is
 * `noindex, follow` and leaves the sitemap (the API's `GET /v1/members/crawl-index` leaves it out). Bio length is
 * deliberately not a bar: Search Console shows member pages with short or AI-written bios getting impressions.
 *
 * The backend has the same rule in `apps/web-api/src/members/member-crawl-index.ts`; change one, change the other.
 */

/** The notices an AI-written bio ends with. They are not the member's bio, so they don't count as text. */
const AI_BIO_NOTICE = /Bio is (?:AI generated|generated by Husky AI)[^.]*\.?/gi;

const NAMED_ENTITIES: Record<string, string> = { nbsp: ' ', amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" };

/** The bio's readable text: tags, entities and AI notices removed, whitespace collapsed. */
export function memberBioText(bio: string | null | undefined): string {
  if (!bio) return '';
  return bio
    .replace(/<[^>]*>/g, ' ')
    .replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (entity, code: string) => {
      if (code[0] !== '#') return NAMED_ENTITIES[code.toLowerCase()] ?? entity;
      const value = code[1] === 'x' || code[1] === 'X' ? parseInt(code.slice(2), 16) : parseInt(code.slice(1), 10);
      return Number.isFinite(value) ? String.fromCodePoint(value) : entity;
    })
    .replace(AI_BIO_NOTICE, ' ')
    .replace(/[\s ]+/g, ' ')
    .trim();
}

/** Whether a member's profile has anything beyond a name: a photo, or bio text of any length. */
export function isMemberIndexable({ bio, hasPhoto }: { bio: string | null | undefined; hasPhoto: boolean }): boolean {
  return hasPhoto || memberBioText(bio).length > 0;
}
